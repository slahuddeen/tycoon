// Concatenates db/migrations/*.sql into supabase/setup.sql: one file you can
// paste into the Supabase SQL editor. The browser's offline mode runs the
// same file inside PGlite.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'db', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

let out = `-- Tycoon database setup (generated by db/bundle.mjs from db/migrations — do not edit by hand).
-- Paste this whole file into the Supabase SQL editor and press Run.
-- Safe to run again after updating: tables are kept, functions are replaced.
`;
for (const f of files) {
  out += `\n-- >>> ${f}\n` + readFileSync(join(dir, f), 'utf8').trim() + '\n';
}
mkdirSync(join(root, 'supabase'), { recursive: true });
writeFileSync(join(root, 'supabase', 'setup.sql'), out);
console.log(`supabase/setup.sql written from ${files.length} migrations`);
